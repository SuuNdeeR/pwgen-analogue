#ifndef RANDOM_H
#define RANDOM_H

// Инициализирует модуль работы с /dev/urandom.
// Возвращает 0 при успехе, или 2 в случае ошибки.
int random_init(void);

// Освобождает ресурсы и закрывает дескриптор файла.
void random_cleanup(void);

// Возвращает случайное число в диапазоне [0, max) без эффекта смещения модуля.
// В случае ошибки или некорректного max возвращает 0.
int random_index(int max);

#endif